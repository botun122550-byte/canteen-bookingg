-- รันหลังจาก orders.sql

with s as (
  insert into shops (name) values
    ('ร้านข้าวแกง'),
    ('ร้านก๋วยเตี๋ยว'),
    ('ร้านน้ำ')
  returning id, name
)
insert into menu_items (shop_id, name, price)
select s.id, m.item, m.price
from s
join (values
  ('ร้านข้าวแกง', 'ข้าวกะเพราหมูสับไข่ดาว', 50),
  ('ร้านข้าวแกง', 'ข้าวผัดหมู', 45),
  ('ร้านข้าวแกง', 'ข้าวราดแกงเขียวหวานไก่', 50),
  ('ร้านข้าวแกง', 'ข้าวมันไก่', 45),
  ('ร้านก๋วยเตี๋ยว', 'ก๋วยเตี๋ยวหมูน้ำใส', 40),
  ('ร้านก๋วยเตี๋ยว', 'ก๋วยเตี๋ยวเรือ', 45),
  ('ร้านก๋วยเตี๋ยว', 'เย็นตาโฟ', 45),
  ('ร้านน้ำ', 'ชาไทยเย็น', 30),
  ('ร้านน้ำ', 'กาแฟเย็น', 35),
  ('ร้านน้ำ', 'น้ำเปล่า', 10)
) as m(shop, item, price) on m.shop = s.name;
